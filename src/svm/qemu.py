"""Render QEMU configuration and command lines."""

from __future__ import annotations

import os
import shutil
import subprocess
import time
from pathlib import Path
from typing import Any

from .config import Config
from .identity import smbios_args
from .state import Session, StateError


def q(value: Any) -> str:
    """Quote a value for QEMU's -readconfig parser."""
    text = str(value).replace("\\", "\\\\").replace('"', '\\"')
    return f'"{text}"'


def qemu_bin(cfg: Config) -> Path:
    if cfg.paths.qemu_bin is None:
        raise StateError("qemu-system-x86_64 not found. Run: sudo ./bootstrap.sh")
    return cfg.paths.qemu_bin


def qemu_version(cfg: Config) -> str:
    binary = qemu_bin(cfg)
    try:
        result = subprocess.run(
            [str(binary), "--version"], capture_output=True, text=True, timeout=10
        )
        return result.stdout.splitlines()[0] if result.stdout else "unknown"
    except (OSError, subprocess.SubprocessError):
        return "unknown"


def is_patched(cfg: Config) -> bool:
    """The anti-detection patch replaces QEMU strings with ASUS strings."""
    binary = qemu_bin(cfg)
    try:
        with binary.open("rb") as handle:
            tail = b""
            while chunk := handle.read(4 * 1024 * 1024):
                data = tail + chunk
                if b"ASUS" in data:
                    return True
                tail = data[-4:]
    except OSError:
        return False
    return False


def _pflash(cfg: Config, session: Session, secure_boot: bool) -> list[str]:
    ovmf = cfg.paths.ovmf
    if ovmf is None:
        raise StateError(
            "OVMF firmware not found. Install the 'ovmf' package (sudo ./bootstrap.sh)."
        )
    if secure_boot:
        if not ovmf.secure_boot_available:
            raise StateError(
                "Secure Boot requested but OVMF Secure Boot firmware is missing."
            )
        code = ovmf.code_sb
    else:
        code = ovmf.code
    assert code is not None
    args = [
        "-drive",
        f"if=pflash,format=raw,unit=0,readonly=on,file={code}",
        "-drive",
        f"if=pflash,format=raw,unit=1,file={session.vars}",
    ]
    if secure_boot:
        args += ["-global", "driver=cfi.pflash01,property=secure,value=on"]
    return args


def render_hardware_config(
    cfg: Config,
    session: Session,
    profile: dict[str, Any],
    *,
    install_iso: Path | None = None,
    driver_iso: Path | None = None,
) -> str:
    identity = session.data["identity"]
    cpu = identity["cpu"]
    disk = identity["disk"]
    display = profile.get("display", {})
    network = profile.get("network", {})
    input_mode = str(profile.get("input", {}).get("mode", "ps2"))
    if input_mode not in {"ps2", "usb"}:
        raise StateError(f"unsupported input.mode '{input_mode}' (use ps2 or usb)")
    audio = bool(display.get("audio", True))
    video = str(display.get("video", "qxl"))
    xres = int(display.get("xres", 1920))
    yres = int(display.get("yres", 1080))
    if video != "qxl":
        raise StateError(f"unsupported display.video '{video}' (only qxl is implemented)")
    mode = str(network.get("mode", "user"))
    if mode != "user":
        raise StateError(f"unsupported network.mode '{mode}' (only user/slirp is implemented)")
    nic = str(network.get("nic", "e1000e"))
    if nic not in {"e1000e", "e1000"}:
        raise StateError(f"unsupported network.nic '{nic}' (use e1000e or e1000)")

    subnet = str(network.get("subnet", "192.168.1.0/24"))
    gateway = str(network.get("gateway", "192.168.1.1"))
    dhcp_start = str(network.get("dhcp_start", "192.168.1.100"))
    dns = str(network.get("dns", "192.168.1.2"))
    ipv6 = bool(network.get("ipv6", False))
    if dns == gateway:
        raise StateError("network.dns must differ from network.gateway for QEMU slirp")

    lines: list[str] = []
    add = lines.append

    add("# Generated by svm. Do not edit; it is rewritten per session.")
    add("")

    # Storage -------------------------------------------------------------
    # During an install the CD must boot first: an empty base disk has no
    # bootloader, and bootindex overrides -boot order. Give the CD index 1 and
    # the disk index 2, then swap them back for normal (non-install) runs.
    add('[device "sata-disk"]')
    add('  driver = "ide-hd"')
    add('  bus = "ide.0"')
    add('  drive = "disk"')
    add(f'  model = {q(disk["model"])}')
    add(f'  serial = {q(disk["serial"])}')
    add(f'  ver = {q(disk["firmware"])}')
    # ATA IDENTIFY word 217: 1 means non-rotating (SSD). Without this Linux
    # reports the SSD as rotational (ROTA=1), which contradicts the model.
    add('  rotation_rate = "1"')
    add(f'  bootindex = {q("2" if install_iso is not None else "1")}')
    add("")
    add('[drive "disk"]')
    add(f'  file = {q(session.disk)}')
    add('  format = "qcow2"')
    add('  if = "none"')
    add('  cache = "writeback"')
    add('  discard = "unmap"')
    add("")

    # Store absolute paths: QEMU may be started from any working directory.
    if install_iso is not None:
        install_iso = Path(install_iso).resolve()
    if driver_iso is not None:
        driver_iso = Path(driver_iso).resolve()

    if install_iso is not None:
        add('[device "sata-cd"]')
        add('  driver = "ide-cd"')
        add('  bus = "ide.1"')
        add('  drive = "cd0"')
        add('  bootindex = "1"')
        add("")
        add('[drive "cd0"]')
        add(f'  file = {q(install_iso)}')
        add('  format = "raw"')
        add('  if = "none"')
        add('  media = "cdrom"')
        add('  readonly = "on"')
        add("")

    if driver_iso is not None:
        add('[device "sata-drivers"]')
        add('  driver = "ide-cd"')
        add('  bus = "ide.2"')
        add('  drive = "cd1"')
        add("")
        add('[drive "cd1"]')
        add(f'  file = {q(driver_iso)}')
        add('  format = "raw"')
        add('  if = "none"')
        add('  media = "cdrom"')
        add('  readonly = "on"')
        add("")

    # PCIe root ports (realistic q35 topology) -----------------------------
    for index in range(4):
        add(f'[device "pcie-port-{index + 1}"]')
        add('  driver = "ioh3420"')
        add('  multifunction = "on"')
        add('  bus = "pcie.0"')
        add(f'  addr = "1c.{index}"')
        add(f'  port = "{index + 1}"')
        add(f'  chassis = "{index + 1}"')
        add("")

    add('[device "pci-bridge"]')
    add('  driver = "i82801b11-bridge"')
    add('  bus = "pcie.0"')
    add('  addr = "1e.0"')
    add("")

    # Network -------------------------------------------------------------
    # Use a normal-looking private subnet instead of QEMU's famous
    # 10.0.2.0/24. WARP inside the guest is still the egress path; slirp is
    # only the local link. No host forwards are configured.
    add('[netdev "net0"]')
    add('  type = "user"')
    add(f'  hostname = {q(identity["hostname"])}')
    add('  domainname = "lan"')
    add(f'  net = {q(subnet)}')
    add(f'  host = {q(gateway)}')
    add(f'  dhcpstart = {q(dhcp_start)}')
    add(f'  dns = {q(dns)}')
    add(f'  ipv6 = {q("on" if ipv6 else "off")}')
    add("")
    add('[device "nic"]')
    add(f'  driver = {q(nic)}')
    add('  netdev = "net0"')
    add(f'  mac = {q(identity["mac"])}')
    add('  bus = "pcie.0"')
    add('  addr = "19.0"')
    add('  romfile = ""')
    add("")

    # Display -------------------------------------------------------------
    add('[device "video"]')
    add(f'  driver = {q(video + "-vga")}')
    add('  bus = "pcie.0"')
    add('  addr = "01.0"')
    add('  ram_size = "67108864"')
    add('  vram_size = "67108864"')
    add('  vgamem_mb = "64"')
    add(f'  xres = "{xres}"')
    add(f'  yres = "{yres}"')
    add("")

    # USB (ICH9 EHCI + three UHCI companions) ------------------------------
    add('[device "ich9-ehci-1"]')
    add('  driver = "ich9-usb-ehci1"')
    add('  multifunction = "on"')
    add('  bus = "pcie.0"')
    add('  addr = "1d.7"')
    add("")
    for index in range(3):
        add(f'[device "ich9-uhci-{index + 1}"]')
        add(f'  driver = "ich9-usb-uhci{index + 1}"')
        add('  multifunction = "on"')
        add('  bus = "pcie.0"')
        add(f'  addr = "1d.{index}"')
        add('  masterbus = "ich9-ehci-1.0"')
        add(f'  firstport = "{index * 2}"')
        add("")

    # Second EHCI/UHCI group, as on a real ICH9 southbridge.
    add('[device "ich9-ehci-2"]')
    add('  driver = "ich9-usb-ehci2"')
    add('  multifunction = "on"')
    add('  bus = "pcie.0"')
    add('  addr = "1a.7"')
    add("")
    for index in range(3):
        add(f'[device "ich9-uhci-{index + 4}"]')
        add(f'  driver = "ich9-usb-uhci{index + 4}"')
        add('  multifunction = "on"')
        add('  bus = "pcie.0"')
        add(f'  addr = "1a.{index}"')
        add('  masterbus = "ich9-ehci-2.0"')
        add(f'  firstport = "{index * 2}"')
        add("")

    # PS/2 input is provided by q35's i8042 controller and is the default.
    # This deliberately avoids usb-tablet/usb-kbd: QEMU's USB HID devices
    # expose 0627:0001, which lsusb resolves to "QEMU Tablet". A real
    # desktop with PS/2 peripherals is both quieter and more plausible.
    if input_mode == "usb":
        add('[device "usb-tablet"]')
        add('  driver = "usb-tablet"')
        add('  bus = "ich9-ehci-1.0"')
        add("")
        add('[device "usb-kbd"]')
        add('  driver = "usb-kbd"')
        add('  bus = "ich9-ehci-1.0"')
        add("")

    # Audio ---------------------------------------------------------------
    add('[device "ich9-hda-audio"]')
    add('  driver = "ich9-intel-hda"')
    add('  bus = "pcie.0"')
    add('  addr = "1b.0"')
    add("")
    add('[device "ich9-hda-duplex"]')
    add('  driver = "hda-duplex"')
    add('  bus = "ich9-hda-audio.0"')
    add('  cad = "0"')
    add('  audiodev = "audio0"')
    add("")
    add('[audiodev "audio0"]')
    add(f'  driver = {q("pa" if audio else "none")}')
    if audio:
        add('  in.mixing-engine = "on"')
        add('  out.mixing-engine = "on"')
    add("")

    # Keep the generated file deterministic for easier diffing.
    return "\n".join(lines) + "\n"


def build_command(
    cfg: Config,
    session: Session,
    *,
    install_iso: Path | None = None,
    driver_iso: Path | None = None,
    no_sandbox: bool = False,
    debug: bool = False,
    write_config: bool = True,
) -> list[str]:
    profile = cfg.profile(str(session.data["profile"]))
    identity = session.data["identity"]
    cpu = identity["cpu"]
    hardware = profile.get("hardware", {})
    resources = profile.get("resources", {})
    display = profile.get("display", {})
    machine_type = str(hardware.get("machine", "q35"))
    firmware = str(hardware.get("firmware", "ovmf"))
    disk_bus = str(hardware.get("disk_bus", "sata"))
    backend = str(display.get("backend", "spice"))
    if machine_type != "q35":
        raise StateError(f"unsupported hardware.machine '{machine_type}' (only q35)")
    if firmware != "ovmf":
        raise StateError(f"unsupported hardware.firmware '{firmware}' (only ovmf)")
    if disk_bus != "sata":
        raise StateError(f"unsupported hardware.disk_bus '{disk_bus}' (only sata)")
    if backend != "spice":
        raise StateError(f"unsupported display.backend '{backend}' (only spice)")
    secure_boot = bool(hardware.get("secure_boot", False))
    tpm = bool(hardware.get("tpm", False))
    sandbox = bool(hardware.get("sandbox", True))
    memory_mb = int(resources.get("memory_mb", 8192))
    os_name = str(profile.get("os", "windows"))

    binary = qemu_bin(cfg)
    rendered = render_hardware_config(
        cfg,
        session,
        profile,
        install_iso=install_iso,
        driver_iso=driver_iso,
    )
    if write_config:
        session.hw_config.write_text(rendered, encoding="utf-8")
        os.chmod(session.hw_config, 0o600)

    # usb=off disables q35's built-in 1d EHCI/UHCI pair so the generated
    # hardware.cfg can describe the complete ICH9 USB topology itself.
    machine = f"{machine_type},accel=kvm,kernel_irqchip=on,vmport=off,usb=off"
    if secure_boot:
        machine += ",smm=on"

    cpu_arg = ",".join(
        [
            "host",
            f"family={cpu['family']}",
            f"model={cpu['model']}",
            f"stepping={cpu['stepping']}",
            f"model-id={cpu['name']}",
            "kvm=off",
            "hypervisor=off",
            "vmware-cpuid-freq=false",
            "enforce=false",
            "host-phys-bits=true",
            # Expose AMD CPUID 0x8000001E. Without it Linux falls back to
            # legacy topology and reports 8 sockets/1 thread for a 4C/8T CPU.
            "topoext=on",
        ]
    )

    cores = int(cpu["cores"])
    threads = int(cpu["threads"])
    per_core = max(1, threads // cores)
    smp = f"{threads},sockets=1,cores={cores},threads={per_core}"

    args: list[str] = [
        str(binary),
        "-name",
        f"{identity['hostname']},process=svm-{session.id}",
        "-machine",
        machine,
        "-cpu",
        cpu_arg,
        "-smp",
        smp,
        "-m",
        f"{memory_mb}M",
        "-uuid",
        str(identity["uuid"]),
        *smbios_args(identity),
        "-rtc",
        f"base={'localtime' if os_name == 'windows' else 'utc'},driftfix=slew",
        "-boot",
        "order=d" if install_iso is not None else "order=c",
        "-nodefaults",
        "-display",
        "none",
        "-monitor",
        "none",
        "-serial",
        "none",
        "-parallel",
        "none",
        "-readconfig",
        str(session.hw_config),
        "-qmp",
        f"unix:{session.qmp},server=on,wait=off",
        "-pidfile",
        str(session.pidfile),
        "-msg",
        "timestamp=on",
        *_pflash(cfg, session, secure_boot),
    ]

    if debug:
        args += ["-D", str(session.log), "-d", "guest_errors"]

    if sandbox and not no_sandbox:
        args += [
            "-sandbox",
            "on,obsolete=deny,elevateprivileges=deny,spawn=deny,resourcecontrol=deny",
        ]

    # Always expose SPICE on the session's Unix socket, even with --headless.
    # Headless means "do not launch a viewer"; it still lets you attach later
    # with `svm attach` or a viewer pointed at the socket. There is no TCP
    # listener either way.
    args += [
        "-spice",
        f"unix=on,addr={session.spice},disable-ticketing=on,"
        "disable-copy-paste=on,disable-agent-file-xfer=on,agent-mouse=off,"
        "image-compression=off,playback-compression=off,streaming-video=off",
    ]

    if tpm:
        tpm_dir = session.tpm_dir
        if tpm_dir is None:
            raise StateError("TPM requested but session has no TPM directory")
        args += [
            "-chardev",
            f"socket,id=chrtpm,path={tpm_dir / 'swtpm.sock'}",
            "-tpmdev",
            "emulator,id=tpm0,chardev=chrtpm",
            "-device",
            "tpm-crb,tpmdev=tpm0",
        ]

    return args


def viewer_command(cfg: Config, session: Session) -> list[str]:
    profile = cfg.profile(str(session.data["profile"]))
    preferred = str(profile.get("general", {}).get("viewer", "remote-viewer"))
    viewer = shutil.which(preferred) or shutil.which("remote-viewer") or shutil.which("spicy")
    if viewer is None:
        raise StateError(
            "no SPICE viewer found. Install virt-viewer or use --headless."
        )
    uri = f"spice+unix://{session.spice}"
    cmd = [viewer]
    if "remote-viewer" in Path(viewer).name:
        cmd.append("--hotkeys=release-cursor=ctrl+alt")
    cmd.append(uri)
    return cmd


def wait_for_socket(path: Path, timeout: float = 15.0) -> bool:
    deadline = time.monotonic() + timeout
    while time.monotonic() < deadline:
        if path.exists():
            return True
        time.sleep(0.1)
    return False


def tail(path: Path, lines: int = 30) -> str:
    try:
        content = path.read_text(encoding="utf-8", errors="replace").splitlines()
    except OSError:
        return ""
    return "\n".join(content[-lines:])
